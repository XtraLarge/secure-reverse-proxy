--
-- admin-apikeys.lua — API Key Management for Proxy Admin Interface
--
-- Included from admin.lua for API key CRUD operations.
-- Keys stored in /etc/apache2/config/apikeys/<sitename>.keys
--

local APIKEY_DIR = "/etc/apache2/config/apikeys/"

-- Generate a secure random API key (32 hex chars = 128 bits)
local function generate_apikey()
    local f = io.open("/dev/urandom", "rb")
    if not f then return nil end
    local bytes = f:read(16)
    f:close()
    if not bytes or #bytes < 16 then return nil end
    
    local hex = ""
    for i = 1, #bytes do
        hex = hex .. string.format("%02x", string.byte(bytes, i))
    end
    return hex
end

-- Load API keys for a site
local function load_apikeys(sitename)
    local keys = {}
    local filepath = APIKEY_DIR .. sitename .. ".keys"
    local f = io.open(filepath, "r")
    if not f then return keys end
    
    local lineno = 0
    for line in f:lines() do
        lineno = lineno + 1
        line = line:match("^%s*(.-)%s*$")  -- trim
        if line ~= "" and not line:match("^#") then
            -- Format: key [label] [created:timestamp]
            local key, rest = line:match("^(%S+)%s*(.*)$")
            if key then
                local label = rest:match("^([^#]+)") or ""
                label = label:match("^%s*(.-)%s*$") or ""
                table.insert(keys, {
                    key = key,
                    label = label,
                    lineno = lineno,
                    masked = key:sub(1,8) .. "..." .. key:sub(-4)
                })
            end
        end
    end
    f:close()
    return keys
end

-- Save API keys for a site
local function save_apikeys(sitename, keys)
    local filepath = APIKEY_DIR .. sitename .. ".keys"
    local f = io.open(filepath, "w")
    if not f then return false, "Cannot write to " .. filepath end
    
    f:write("# API keys for " .. sitename .. "\n")
    f:write("# Format: <key> [label]\n")
    f:write("# Generated by admin-apikeys.lua\n\n")
    
    for _, k in ipairs(keys) do
        if k.label and k.label ~= "" then
            f:write(k.key .. " " .. k.label .. "\n")
        else
            f:write(k.key .. "\n")
        end
    end
    f:close()
    
    -- chmod 640 for www-data readability
    os.execute("chmod 640 " .. filepath .. " && chown www-data:www-data " .. filepath)
    return true
end

-- List all sites with API keys configured
local function list_apikey_sites()
    local sites = {}
    local p = io.popen("ls " .. APIKEY_DIR .. "*.keys 2>/dev/null")
    if p then
        for f in p:lines() do
            local sitename = f:match("/([^/]+)%.keys$")
            if sitename then
                table.insert(sites, sitename)
            end
        end
        p:close()
    end
    return sites
end

-- === HTTP Handlers ===

-- Show API keys list for a site
function show_apikeys(r, sitename, msg)
    local h = function(s) return (s or ""):gsub("&","&amp;"):gsub("<","&lt;"):gsub(">","&gt;"):gsub('"',"&quot;") end
    
    r:puts([[<!DOCTYPE html><html><head>
        <meta charset="UTF-8">
        <title>API Keys – ]] .. h(sitename) .. [[</title>
        <link rel="stylesheet" href="/res/style.css">
    </head><body>
        <h1>🔑 API Keys: ]] .. h(sitename) .. [[</h1>]])
    
    if msg then
        local cls = msg:match("^ERR") and "error" or "success"
        r:puts('<div class="' .. cls .. '">' .. h(msg) .. '</div>')
    end
    
    r:puts([[<p><a href="?action=list">← Zurück zur Übersicht</a></p>]])
    
    local keys = load_apikeys(sitename)
    
    if #keys == 0 then
        r:puts([[<p>Keine API-Keys vorhanden.</p>]])
    else
        r:puts([[<table class="toc">
            <tr><th>Key (maskiert)</th><th>Label</th><th>Aktionen</th></tr>]])
        for _, k in ipairs(keys) do
            r:puts('<tr>')
            r:puts('<td><code>' .. h(k.masked) .. '</code></td>')
            r:puts('<td>' .. h(k.label) .. '</td>')
            r:puts('<td>')
            r:puts('<form method="POST" style="display:inline" onsubmit="return confirm(\'Key wirklich löschen?\')">')
            r:puts('<input type="hidden" name="action" value="apikey_delete">')
            r:puts('<input type="hidden" name="site" value="' .. h(sitename) .. '">')
            r:puts('<input type="hidden" name="key" value="' .. h(k.key) .. '">')
            r:puts('<button type="submit" class="btn-danger">🗑️ Löschen</button>')
            r:puts('</form>')
            r:puts('</td>')
            r:puts('</tr>')
        end
        r:puts([[</table>]])
    end
    
    -- Add new key form
    r:puts([[
        <h2>Neuen Key erstellen</h2>
        <form method="POST">
            <input type="hidden" name="action" value="apikey_create">
            <input type="hidden" name="site" value="]] .. h(sitename) .. [[">
            <label>Label (optional): <input type="text" name="label" placeholder="z.B. Claude Code"></label>
            <button type="submit" class="btn-primary">🔑 Key generieren</button>
        </form>
    ]])
    
    r:puts([[</body></html>]])
end

-- Create a new API key
function do_apikey_create(r, post)
    local sitename = post["site"] or ""
    local label = (post["label"] or ""):match("^%s*(.-)%s*$") or ""
    
    if sitename == "" then
        show_list(r, "ERR: Kein Sitename")
        return
    end
    
    local newkey = generate_apikey()
    if not newkey then
        show_apikeys(r, sitename, "ERR: Konnte keinen Key generieren")
        return
    end
    
    local keys = load_apikeys(sitename)
    table.insert(keys, { key = newkey, label = label })
    
    local ok, err = save_apikeys(sitename, keys)
    if not ok then
        show_apikeys(r, sitename, "ERR: " .. (err or "Speichern fehlgeschlagen"))
        return
    end
    
    -- Show the new key ONCE (full, not masked)
    r:puts([[<!DOCTYPE html><html><head>
        <meta charset="UTF-8">
        <title>Neuer API Key erstellt</title>
        <link rel="stylesheet" href="/res/style.css">
    </head><body>
        <h1>✅ Neuer API Key erstellt</h1>
        <div class="success">
            <p><strong>WICHTIG:</strong> Der Key wird nur einmal angezeigt!</p>
            <p>Key: <code style="background:#fff;padding:5px;font-size:1.2em">]] .. newkey .. [[</code></p>
            <p>Label: ]] .. (label ~= "" and label or "<em>keins</em>") .. [[</p>
        </div>
        <p><a href="?action=apikeys&site=]] .. sitename .. [[">← Zurück zu den Keys</a></p>
    </body></html>]])
end

-- Delete an API key
function do_apikey_delete(r, post)
    local sitename = post["site"] or ""
    local keyval = post["key"] or ""
    
    if sitename == "" or keyval == "" then
        show_list(r, "ERR: Parameter fehlen")
        return
    end
    
    local keys = load_apikeys(sitename)
    local newkeys = {}
    local found = false
    
    for _, k in ipairs(keys) do
        if k.key == keyval then
            found = true
        else
            table.insert(newkeys, k)
        end
    end
    
    if not found then
        show_apikeys(r, sitename, "ERR: Key nicht gefunden")
        return
    end
    
    local ok, err = save_apikeys(sitename, newkeys)
    if not ok then
        show_apikeys(r, sitename, "ERR: " .. (err or "Speichern fehlgeschlagen"))
        return
    end
    
    show_apikeys(r, sitename, "Key gelöscht")
end

return {
    show_apikeys = show_apikeys,
    do_apikey_create = do_apikey_create,
    do_apikey_delete = do_apikey_delete,
    list_apikey_sites = list_apikey_sites
}
